/* wiki 副词条默认是 id 列表（按优先级），转成 app 内部 [{id, req, op, opt}]；
   兼容手工数据格式：[id, req, op?]，例如：
   subs: [['cr', 1], ['cd', 1, '='], ['atkP']]
   字符串写法不再自动标记首位；只有显式元组或 subRules 的 required 才会成为 ★必选。 */

function subIdsToSubs(ids, subRules) {
  const out = toSubs((ids || []).map((item, i) => {
    if (Array.isArray(item)) return [item[0], item[1], item[2], item[3]];
    if (item && typeof item === 'object') {
      return [item.id != null ? item.id : item.stat, item.req, item.op, item.opt];
    }
    return [item, false, '>'];
  }));
  const rules = subRules && typeof subRules === 'object' ? subRules : {};
  const required = new Set(Array.isArray(rules.required) ? rules.required : []);
  out.forEach(item => { if (required.has(item.id)) item.req = true; });
  (Array.isArray(rules.equal) ? rules.equal : []).forEach(group => {
    if (!Array.isArray(group) || group.length < 2) return;
    const positions = group.map(id => out.findIndex(item => item.id === id)).filter(i => i >= 0);
    positions.sort((a, b) => a - b).slice(1).forEach(i => { out[i].op = '='; });
  });
  /* 条件词条（subRules.optional）：wiki 原文写的是「搭配西风猎弓就堆暴击率」这类
   * 有前提的推荐，既不算常规推荐、也不能丢——标 opt 供 UI 单独提示。
   * 注意：required 就是直接从 subs 里挑，不再做「= 首位核心块」收紧，
   * 否则 subRules.required 会被前端清空成死字段（历史上 122 组踩过这个坑）。 */
  /* optional 支持两种写法：
   *   - 旧：['cr']                      纯字符串列表
   *   - 新：[['cr','携带西风秘典时']]      [stat, note] 元组，note 是「为什么是条件词条」的理由
   * 统一规整成 stat -> note 映射，note 可为空串（回退到通用说明）。 */
  const optNoteOf = {};
  (Array.isArray(rules.optional) ? rules.optional : []).forEach(p => {
    const stat = Array.isArray(p) ? String(p[0] || '') : String(p);
    const note = Array.isArray(p) ? String(p[1] || '') : '';
    if (stat) optNoteOf[stat] = note;
  });
  out.forEach(item => {
    if (item.id in optNoteOf && !item.req) { item.opt = true; item.optNote = optNoteOf[item.id]; }
  });
  /* optional 里也可能有「没进常规 subs」的词条（wiki 只把它写成条件推荐，
   * 例如「暴击率（携带西风剑时）」）——补到末尾标 opt，别让词条凭空消失。 */
  Object.keys(optNoteOf).forEach(stat => {
    if (out.some(item => item.id === stat)) return;
    if (!SUB_STATS.some(s => s.id === stat)) return;
    out.push({ id: stat, req: false, op: '>', opt: true, optNote: optNoteOf[stat] });
  });
  return out;
}

function normalizeSubRules(rules) {
  const r = rules && typeof rules === 'object' ? rules : {};
  return {
    required: Array.isArray(r.required) ? r.required.filter(id => typeof id === 'string') : [],
    equal: Array.isArray(r.equal)
      ? r.equal.filter(group => Array.isArray(group) && group.length > 1)
        .map(group => group.filter(id => typeof id === 'string'))
      : [],
    optional: Array.isArray(r.optional)
      ? r.optional.map(o => Array.isArray(o)
          ? [String(o[0] || ''), String(o[1] || '')]
          : [String(o), ''])
        .filter(p => p[0])
      : [],
    source: r.source === 'manual' || r.source === 'heuristic' ? r.source : 'unset',
  };
}

/* 把来源链接项归一化为 {url, title}（兼容旧版纯字符串 / [url,title] 数组 / 对象） */
function normSrcItem(s) {
  if (!s) return null;
  if (typeof s === 'string') return { url: s.trim(), title: '' };
  if (Array.isArray(s)) return { url: String(s[0] || '').trim(), title: String(s[1] || '').trim() };
  if (typeof s === 'object') return { url: String(s.url || '').trim(), title: String(s.title || '').trim() };
  return null;
}
function normSrcList(list) {
  if (!Array.isArray(list)) return [];
  return list.map(normSrcItem).filter(x => x && x.url);
}

function buildDefaultCharacters() {
  return RAW_CHARS.map((row, i) => {
    const name = row[0];
    const element = row[1];
    const meta = CHAR_META[name] || { region: 'other', roles: ['maindps'] };

    // 数据格式兼容：
    //   新格式：[name, element, [ {sets,sands,goblet,circlet,subs,tag}... ], src, note]
    //   旧格式（兜底）：[name, element, subPreset, [sets...], sands[], goblet[], circlet[], src, note]
    let buildsRaw, srcRaw, noteRaw;
    if (Array.isArray(row[2])) {
      buildsRaw = row[2]; srcRaw = row[3]; noteRaw = row[4];
    } else {
      const subPreset = row[2];
      const setsList = row[3] || [];
      const fn = (arr) => (arr || []).map((stat, j) => ({ stat, rank: j + 1 }));
      const presets = SUB_PRESETS[subPreset] || SUB_PRESETS.crit;
      buildsRaw = setsList.map(sets => ({
        sets,
        sands: fn(row[4]), goblet: fn(row[5]), circlet: fn(row[6]),
        subs: presets, tag: null,
      }));
      srcRaw = row[7]; noteRaw = row[8];
    }

    // 每组配装独立携带 套装 + 主词条 + 副词条（直接来自 wiki，不再走粗预设桶）
    const builds = buildsRaw.map((b, idx) => ({
      sets: b.sets || [],
      bkey: name + '#' + idx,
      priority: idx === 0 ? 'main' : 'alt',
      main: {
        sands:   (b.sands   || []).map((stat, j) => ({ stat, rank: j + 1 })),
        goblet:  (b.goblet  || []).map((stat, j) => ({ stat, rank: j + 1 })),
        circlet: (b.circlet || []).map((stat, j) => ({ stat, rank: j + 1 })),
      },
      subRules: normalizeSubRules(b.subRules),
      subs: subIdsToSubs(b.subs, b.subRules),
      roles: Array.isArray(b.roles) ? b.roles.filter(s => typeof s === 'string' && s) : [],
    }));

    return {
      id: 'c' + i + '_' + name,
      name,
      skey: name, // 出厂角色名：改名后不变，是「改名了还能还原」的唯一可靠锚点（id 会随数组插入漂移）
      element,
      region: meta.region,
      roles: meta.roles.slice(),
      enabled: false,
      note: noteRaw || '',
      src: normSrcList(srcRaw),
      custom: false,
      builds,
    };
  });
}

